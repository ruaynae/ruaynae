-- ที่หนังสือบริษัทดึงไปใส่ย่อหน้าแนะนำ ("ข้าพเจ้า … เป็นผู้รับจ้าง{โครงการ} ณ {สถานที่} …")
-- · ว่างได้ — หนังสือใช้ชื่อย่อแทน · RLS เดิมของ `sites` คุมคอลัมน์นี้ไปด้วย (หัวหน้าโครงการเห็นได้ เหมือนชื่อ)
-- · audit trigger เดิมเก็บ before/after ทั้งแถวอยู่แล้ว ไม่ต้องเพิ่ม

alter table public.sites
  add column if not exists full_name text check (full_name is null or length(full_name) <= 500);

comment on column public.sites.full_name is 'ชื่อโครงการเต็มตามสัญญา (หนังสือบริษัทใช้) · name = ชื่อย่อที่ใช้เลือกในระบบ';
