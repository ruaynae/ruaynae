/** รหัสความผิดพลาดจากฐานข้อมูล → ข้อความไทย (รหัสอยู่หน้าเครื่องหมาย ":" ของข้อความ) */
export function dbErrorText(message: string): string {
  const code = message.split(':')[0]?.trim() ?? ''
  if (code === 'DATE_FUTURE') return copy.exp.future
  if (code === 'PAYROLL_CLOSED') return 'วันนั้นจ่ายค่าแรงไปแล้ว แก้ไม่ได้'
  return copy.failed
}
