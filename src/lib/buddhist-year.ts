/**
 * ปีในช่องวันที่ที่เป็น พ.ศ. แน่นอน (2400–2799 ≈ ค.ศ. 1857–2256) → ลบ 543 เป็น ค.ศ.
 * · รับ `YYYY-MM-DD` หรือ `YYYY-MM` (ช่องเดือน) · ค่าอื่นคืนตามเดิม
 * · 29 ก.พ. ของปี พ.ศ. ที่ ค.ศ. ไม่ใช่ปีอธิกสุรทิน จะไม่เกิด — ช่องวันที่ของเบราว์เซอร์ไม่ให้ค่าแบบนั้นอยู่แล้ว
 */
export function fixBuddhistYear(v: string): string {
  const m = /^(\d{4})(-\d{2}(?:-\d{2})?)$/.exec(v)
  if (!m) return v
  const y = Number(m[1])
  return y >= 2400 && y < 2800 ? `${y - 543}${m[2]}` : v
}
