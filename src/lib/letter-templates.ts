/** ค่าที่ระบบคิดให้เองจากทะเบียน — ไม่ต้องให้คนนับ */
export type LetterAuto = 'materialNext' | 'deliveryNext' | 'prevMonth'

export type LetterField = {
  k: string
  label: string
  /** `date` = ปฏิทิน แต่ค่าที่เก็บ/ลงกระดาษยังเป็นข้อความ "3 พฤศจิกายน 2569" (`thaiDate`) */
  type?: 'text' | 'number' | 'select' | 'money' | 'date'
  def?: string
  ph?: string
  /** ตัวเลือกช่วยพิมพ์ (datalist) */
  list?: readonly string[]
  options?: readonly string[]
  auto?: LetterAuto
  wide?: boolean
}

export type LetterTemplate = {
  id: string
  name: string
  /** จับคู่เรื่องของหนังสือเก่าในทะเบียน — ใช้นับ "เคยออก n ฉบับ" และทำซ้ำ */
  match: RegExp | null
  fields?: readonly LetterField[]
  subject: string
  atts: readonly string[]
  body: string
  closing?: string
  /** หัวข้อหน้ารูปแนบท้าย (ถ้าแบบนี้มักมีรูป) */
  photoTitle?: string
  photoLayout?: '1' | '2'
}

