export const findLetterTemplate = (id: string | null | undefined) =>
  LETTER_TEMPLATES.find((t) => t.id === id) ?? null

/** แบบที่ตรงกับเรื่องของหนังสือ — ใช้กับหนังสือที่นำเข้ามาโดยไม่มี `template_id` */
export const matchLetterTemplate = (subject: string) =>
  LETTER_TEMPLATES.find((t) => t.match?.test(subject)) ?? null
